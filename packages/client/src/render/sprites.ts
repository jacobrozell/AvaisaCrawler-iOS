export function dirOf(facing: number): FacingDir {
  const c = Math.cos(facing);
  const s = Math.sin(facing);
  if (Math.abs(c) >= Math.abs(s)) return c >= 0 ? 'e' : 'w';
  return s >= 0 ? 's' : 'n';
}

export function npcActorId(npcId: string): string {
  switch (npcId) {
    case 'hessa':
      return 'warden';
    case 'ulric':
      return 'smith';
    case 'pell':
      return 'merchant';
    case 'tavi':
      return 'porter';
    case 'relay_clerk':
      return 'surveyor';
    default:
      return 'civilian';
  }
}

export function actorSprite(id: string, dir: FacingDir, frame: number): SpriteSpec {
  const d = dir === 'w' ? 'e' : dir;
  const key = `${id}-${d}-${frame & 1}`;
  const rows = ACTORS[key] ?? ACTORS[`${id}-${d}-0`] ?? ACTORS[`${id}-s-0`] ?? ACTORS['warden-s-0'];
  if (!rows) throw new Error(`missing actor ${id}`);
  const resolved = ACTORS[key] ? key : ACTORS[`${id}-${d}-0`] ? `${id}-${d}-0` : `${id}-s-0`;
  return { key: resolved, rows, scale: ACTOR_SCALE };
}

export function monsterSprite(monsterId: string, shape: string): SpriteSpec {
  if (shape === 'boss') {
    const rows = BOSSES[monsterId] ?? BOSSES.brother_varn!;
    return { key: `boss:${monsterId}`, rows, scale: 4 };
  }
  const rows = MONSTERS[shape] ?? MONSTERS.cultist!;
  return { key: `mon:${shape}`, rows, scale: ACTOR_SCALE };
}

export function treeSprite(variant: number): SpriteSpec {
  const i = variant % TREES.length;
  return { key: `tree-${i}`, rows: TREES[i]!, scale: ACTOR_SCALE };
}

export function propSprite(name: string): SpriteSpec {
  const rows = PROPS[name] ?? PROPS.lamp!;
  return { key: `prop:${name}`, rows, scale: ACTOR_SCALE };
}

export function dropSprite(rarity: string): SpriteSpec {
  const rows = DROPS[rarity] ?? DROPS.scrap!;
  return { key: `drop:${rarity}`, rows, scale: 4 };
}

export function shardSprite(): SpriteSpec {
  return { key: 'shard', rows: SHARD, scale: 3 };
}

export function iconRows(name: string): string[] | undefined {
  return ICONS[name];
}

export function skillRows(id: string): string[] | undefined {
  return SKILLS[id];
}

export function everyFrame(): { name: string; rows: string[] }[] {
  const out: { name: string; rows: string[] }[] = [];
  for (const [name, rows] of Object.entries(ACTORS)) out.push({ name, rows });
  for (const [name, rows] of Object.entries(MONSTERS)) out.push({ name, rows });
  for (const [name, rows] of Object.entries(BOSSES)) out.push({ name, rows });
  for (const [name, rows] of Object.entries(PROPS)) out.push({ name, rows });
  for (const [name, rows] of Object.entries(DROPS)) out.push({ name, rows });
  for (const [name, rows] of Object.entries(ICONS)) out.push({ name: `icon-${name}`, rows });
  for (const [name, rows] of Object.entries(SKILLS)) out.push({ name: `skill-${name}`, rows });
  TREES.forEach((rows, i) => out.push({ name: `tree-${i}`, rows }));
  out.push({ name: 'shard', rows: SHARD });
  return out;
}
