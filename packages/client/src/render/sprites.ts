const ACTORS: Record<string, string[]> = {};

function add(id: string, dir: 'n' | 's' | 'e', still: string, legs: string): void {
  const label = `${id}-${dir}`;
  let body: string[];
  let step: string[];
  try {
    body = px(still);
  } catch (e) {
    throw new Error(`${label} still: ${(e as Error).message}`);
  }
  try {
    step = px(legs);
  } catch (e) {
    throw new Error(`${label} legs: ${(e as Error).message}`);
  }
  if (step[0]!.length !== body[0]!.length) throw new Error(`${label} leg width ${step[0]!.length} != ${body[0]!.length}`);
  if (step.length > body.length) throw new Error(`${label} legs taller than body`);
  ACTORS[`${label}-0`] = body;
  ACTORS[`${label}-1`] = body.slice(0, body.length - step.length).concat(step);
}

function pose(id: string, src: string): void {
  try {
    ACTORS[`${id}-s-0`] = px(src);
  } catch (e) {
    throw new Error(`${id}: ${(e as Error).message}`);
  }
}

function spr(name: string, src: string): string[] {
  try {
    return px(src);
  } catch (e) {
    throw new Error(`${name}: ${(e as Error).message}`);
  }
}

